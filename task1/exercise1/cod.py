import numpy as np

# 1. Երկու զանգվածների ստեղծում
a = np.array([10, 20, 30, 40, 50])
b = np.array([1, 2, 3, 4, 5])

# 2. Զանգվածների տպում
print("Զանգված a:", a)
print("Զանգված b:", b)
print("-" * 30)

# 3. Գումարը և արտադրյալը (տարր առ տարր)
print("Գումարը (a + b):", a + b)
print("Արտադրյալը (a * b):", a * b)
print("-" * 30)

# 4. Միջին թվաբանականը, մաքսիմումը և մինիմումը (a զանգվածի համար)
print("a-ի միջին թվաբանականը:", np.mean(a))
print("a-ի մաքսիմումը:", np.max(a))
print("a-ի մինիմումը:", np.min(a))
print("-" * 30)

# 5. Shape-ի (չափականության) տպում
print("a-ի shape-ը:", a.shape)
print("b-ի shape-ը:", b.shape)
